package app

import (
	"strings"
	"sync"
)

type tag struct {
	AsEntered string
	URLSlug   string
	Servers   map[string]bool
	//SortedArray []string
	IsGenerated bool   // Indicates a tag is generated by the application
	Prefix      string // prefix for generated tags ("os", "domain", etc.)
}

type tagList struct {
	sync.RWMutex
	Tags tagMap
	//SortedArray   []string
	UserTags      []string
	GeneratedTags []string
}

func (tl *tagList) getTags() tagMap {
	tl.RLock()
	defer tl.RUnlock()
	return tl.Tags
}

type tagMap map[string]tag

func parseTags(s string) ([]string, error) {
	// TODO: Regex on letter[letter-.]
	var tags []string
	t := strings.Split(s, ",")
	for _, v := range t {
		v = strings.TrimSpace(v)
		tags = append(tags, v)
	}
	return tags, nil
}

func (list *ServerList) mapTags() {
	newTagList := make(tagMap)

	serverKeys := list.Keys()
	var tags []string

	// Process each server
	for _, serverKey := range serverKeys {
		list.RLock()
		v, ok := list.Servers[serverKey]
		list.RUnlock()

		if ok {
			v.RLock()
			tags = v.Tags

			// domain tag
			if v.Domain != "" {
				tags = append(tags, "domain-"+v.Domain)
			} else {
				tags = append(tags, "domain-none")
			}

			// edition tag
			switch v.EditionID {
			case 0:
				tags = append(tags, "edition-unknown")
			case 1804890536:
				tags = append(tags, "edition-enterprise-cal")
			case 1872460670:
				tags = append(tags, "edition-enterprise-core")
			case 610778273:
				tags = append(tags, "edition-enterprise-eval")
			case 284895786:
				tags = append(tags, "edition-bizint")
			case -1592396055:
				tags = append(tags, "edition-express")
			case -133711905:
				tags = append(tags, "edition-express-advsvcs")
			case -2117995310:
				tags = append(tags, "edition-developer")
			case -1534726760:
				tags = append(tags, "edition-standard")
			case 1293598313:
				tags = append(tags, "edition-web")
			case 1674378470:
				tags = append(tags, "edition-azure")
			default:
				tags = append(tags, "edition-unknown")
			}

			// os tag
			if v.HostPlatform != "" {
				tags = append(tags, "os-"+strings.ToLower(v.HostPlatform))
			} else if v.MajorVersion <= 13 {
				tags = append(tags, "os-windows") // SQL 2016 and before is Windows only
			} else {
				tags = append(tags, "os-unknown")
			}

			switch v.ContainerType {
			case 0:
				tags = append(tags, "container-none")
			case 1:
				tags = append(tags, "container-linux")
			case 2:
				tags = append(tags, "container-windows")
			case 3:
				tags = append(tags, "container-hyperv")
			default:
				tags = append(tags, "container-unknown")
			}

			// version tag
			sqlVersion := strings.ReplaceAll(v.VersionString, " ", "-")
			if sqlVersion != "" && len(sqlVersion) >= 14 {
				tags = append(tags, sqlVersion[0:15])
			} else {
				tags = append(tags, "sql-server-undefined")
			}
			v.RUnlock()

			// Process each tag
			for _, t := range tags {
				isGenerated := false
				prefix := ""
				lowerT := strings.ToLower(t)

				if strings.HasPrefix(lowerT, "edition-") ||
					strings.HasPrefix(lowerT, "domain-") ||
					strings.HasPrefix(lowerT, "sql-server-") ||
					strings.HasPrefix(lowerT, "os-") ||
					strings.HasPrefix(lowerT, "container-") {
					prefix = strings.Split(lowerT, "-")[0]
					isGenerated = true
				}

				_, ok := newTagList[lowerT]
				if ok {
					newTagList[lowerT].Servers[serverKey] = true
				} else {
					m := make(map[string]bool)
					m[serverKey] = true
					t2 := tag{
						AsEntered:   lowerT,
						URLSlug:     strings.ToLower(t),
						Servers:     m,
						IsGenerated: isGenerated,
						Prefix:      prefix,
					}
					newTagList[lowerT] = t2
				}
			}
		}

	}

	globalTagList.Lock()
	globalTagList.Tags = newTagList
	globalTagList.Unlock()
}
